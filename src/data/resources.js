// Helper function to get all resources as a flat array
export const getAllResources = () => {
  return Object.values(learningResources).flat();
};

// Helper function to get resources by category
export const getResourcesByCategory = (category) => {
  return learningResources[category] || [];
};

// Helper function to filter resources by type (Free/Paid)
export const filterResourcesByType = (resources, type) => {
  if (type === 'All') return resources;
  return resources.filter(resource => resource.type === type);
};

// Helper function to get recommended resources based on user interests
export const getRecommendedResources = (userInterests = []) => {
  if (!userInterests.length) return getAllResources();
  
  const prioritizedCategories = [];
  const otherCategories = [];
  
  Object.keys(learningResources).forEach(category => {
    const isUserInterest = userInterests.some(interest => 
      category.toLowerCase().includes(interest.toLowerCase()) ||
      interest.toLowerCase().includes(category.toLowerCase())
    );
    
    if (isUserInterest) {
      prioritizedCategories.push(...learningResources[category]);
    } else {
      otherCategories.push(...learningResources[category]);
    }
  });
  
  return [...prioritizedCategories, ...otherCategories];
};
